BEGIN;

-- 1. Ekub groups
CREATE TABLE ekub_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,
    description TEXT,

    contribution_frequency VARCHAR(20) NOT NULL
        CHECK (
            contribution_frequency IN (
                'daily', 'every_3_days', 'weekly', 'monthly'
            )
        ),

    start_date DATE NOT NULL,
    end_date DATE NOT NULL,

    contribution_amount NUMERIC(12, 2) NOT NULL
        CHECK (contribution_amount > 0),

    currency CHAR(3) NOT NULL DEFAULT 'ETB'
        CHECK (currency = 'ETB'),

    -- Capacity limits are validated using central ekub_settings.
    capacity INTEGER NOT NULL,

    visibility VARCHAR(10) NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'private')),

    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'open', 'closed', 'cancelled')),

    created_by BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (end_date >= start_date),

    UNIQUE (id, created_by)
);

CREATE INDEX idx_ekub_groups_public
    ON ekub_groups (start_date, id)
    WHERE visibility = 'public' AND status = 'open';

CREATE INDEX idx_ekub_groups_creator
    ON ekub_groups (created_by, status);


-- 2. Invitations to private groups
CREATE TABLE ekub_group_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL
        REFERENCES ekub_groups(id) ON DELETE RESTRICT,

    invited_user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    invited_by BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            status IN (
                'pending',
                'accepted',
                'declined',
                'revoked',
                'expired'
            )
        ),

    expires_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_ekub_invitations_user_status
    ON ekub_group_invitations (invited_user_id, status);

CREATE INDEX idx_ekub_invitations_group_user
    ON ekub_group_invitations (group_id, invited_user_id, status);

-- At most one pending invitation per group/user pair.
CREATE UNIQUE INDEX uq_ekub_pending_invitation
    ON ekub_group_invitations (group_id, invited_user_id)
    WHERE status = 'pending';


-- 3. Membership applications; rejected history is retained
CREATE TABLE ekub_membership_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL
        REFERENCES ekub_groups(id) ON DELETE RESTRICT,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),

    reviewed_by BIGINT
        REFERENCES users(id) ON DELETE RESTRICT,

    reviewed_at TIMESTAMPTZ,
    review_note TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Supports a composite FK from memberships to verify matching
    -- application, group, and user.
    UNIQUE (id, group_id, user_id),

    CHECK (
        (status = 'pending' AND reviewed_at IS NULL)
        OR
        (status IN ('approved', 'rejected') AND reviewed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_ekub_application_active
    ON ekub_membership_applications (group_id, user_id)
    WHERE status IN ('pending', 'approved');

CREATE INDEX idx_ekub_applications_status
    ON ekub_membership_applications (status, created_at);

CREATE INDEX idx_ekub_applications_user
    ON ekub_membership_applications (user_id, status);


-- 4. Memberships
CREATE TABLE ekub_group_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    application_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'left', 'removed')),

    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_membership_application_match
        FOREIGN KEY (application_id, group_id, user_id)
        REFERENCES ekub_membership_applications (id, group_id, user_id)
        ON DELETE RESTRICT,

    UNIQUE (application_id)
);

CREATE UNIQUE INDEX uq_ekub_active_membership
    ON ekub_group_memberships (group_id, user_id)
    WHERE status = 'active';

CREATE INDEX idx_ekub_memberships_user
    ON ekub_group_memberships (user_id, status);

CREATE INDEX idx_ekub_memberships_group
    ON ekub_group_memberships (group_id, status);

COMMIT;
