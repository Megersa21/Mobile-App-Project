
BEGIN;

-- 1. Ekub groups
CREATE TABLE ekub_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    contribution_frequency VARCHAR(20) NOT NULL
        CHECK (contribution_frequency IN (
            'daily', 'every_3_days', 'weekly', 'monthly'
        )),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    contribution_amount NUMERIC(12, 2) NOT NULL
        CHECK (contribution_amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'ETB',
    capacity INTEGER NOT NULL
        CHECK (capacity BETWEEN 1 AND 10000),
    visibility VARCHAR(10) NOT NULL DEFAULT 'public'
        CHECK (visibility IN ('public', 'private')),
    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'open', 'closed', 'cancelled')),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (end_date >= start_date)
);

CREATE INDEX idx_ekub_groups_public
    ON ekub_groups (start_date, id)
    WHERE visibility = 'public' AND status = 'open';

-- 2. Invitations to private groups
CREATE TABLE ekub_group_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES ekub_groups(id),
    invited_user_id BIGINT NOT NULL REFERENCES users(id),
    invited_by BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'declined', 'revoked')),
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_ekub_invitations_user_status
    ON ekub_group_invitations (invited_user_id, status);

-- 3. Membership applications; rejected history is retained
CREATE TABLE ekub_membership_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES ekub_groups(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uq_ekub_application_active
    ON ekub_membership_applications (group_id, user_id)
    WHERE status IN ('pending', 'approved');

CREATE INDEX idx_ekub_applications_status
    ON ekub_membership_applications (status, created_at);

-- 4. Memberships
CREATE TABLE ekub_group_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES ekub_groups(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    application_id BIGINT NOT NULL
        REFERENCES ekub_membership_applications(id),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'left', 'removed')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (application_id)
);

CREATE UNIQUE INDEX uq_ekub_active_membership
    ON ekub_group_memberships (group_id, user_id)
    WHERE status = 'active';

CREATE INDEX idx_ekub_memberships_user
    ON ekub_group_memberships (user_id, status);

COMMIT;
